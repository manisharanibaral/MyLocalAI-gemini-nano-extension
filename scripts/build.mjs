#!/usr/bin/env node
/**
 * Builds the three MyLocalAI editions from the shared source in the repo root.
 *
 *   node scripts/build.mjs            → dist/mylocalai-{nano,ollama,mixed}/
 *   node scripts/build.mjs --zip      → also dist/mylocalai-<edition>.zip (needs `zip`)
 *   node scripts/build.mjs nano       → build only the listed edition(s)
 *
 * Each edition gets its own manifest.json (name, permissions) and config.js
 * (which backends the sidebar may use). Everything else is copied as-is.
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");

// Files the extension actually loads at runtime.
const SHARED_FILES = [
  "background.js",
  "page-watch.js",
  "sidebar.html",
  "sidebar.css",
  "sidebar.js",
  "purify.min.js",
  "marked.umd.js",
  "icons",
];

const OLLAMA_HOSTS = ["http://localhost:11434/*", "http://127.0.0.1:11434/*"];

export const EDITIONS = {
  nano: {
    backends: ["nano"],
    manifest: {
      name: "MyLocalAI — Gemini Nano",
      description: "Chat privately with Gemini Nano, built into Chrome. 100% on-device, zero cloud, nothing else to install.",
      action: { default_title: "Open MyLocalAI (Gemini Nano)" },
      // Prompt API for extensions shipped in Chrome 138.
      minimum_chrome_version: "138",
      // No network access needed at all.
      host_permissions: null,
    },
  },
  ollama: {
    backends: ["ollama"],
    manifest: {
      name: "MyLocalAI — Ollama",
      description: "Chat privately with any local Ollama model, in any Chromium browser. 100% local, zero cloud.",
      action: { default_title: "Open MyLocalAI (Ollama)" },
      host_permissions: OLLAMA_HOSTS,
    },
  },
  mixed: {
    backends: ["nano", "ollama"],
    manifest: {
      name: "MyLocalAI",
      host_permissions: OLLAMA_HOSTS,
    },
  },
};

function buildManifest(base, overrides) {
  const manifest = structuredClone(base);
  for (const [key, value] of Object.entries(overrides)) {
    if (value === null) delete manifest[key];
    else if (key === "action") manifest.action = { ...manifest.action, ...value };
    else manifest[key] = value;
  }
  return manifest;
}

function buildConfig(edition, backends) {
  return `// Generated by scripts/build.mjs — do not edit in dist/.
window.MYLOCALAI_CONFIG = ${JSON.stringify({ edition, backends }, null, 2)};
`;
}

function build(edition, { zip }) {
  const spec = EDITIONS[edition];
  const outDir = join(DIST, `mylocalai-${edition}`);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });

  for (const file of SHARED_FILES) {
    cpSync(join(ROOT, file), join(outDir, file), { recursive: true });
  }

  const baseManifest = JSON.parse(readFileSync(join(ROOT, "manifest.json"), "utf8"));
  const manifest = buildManifest(baseManifest, spec.manifest);
  writeFileSync(join(outDir, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  writeFileSync(join(outDir, "config.js"), buildConfig(edition, spec.backends));

  if (zip) {
    const zipPath = join(DIST, `mylocalai-${edition}.zip`);
    rmSync(zipPath, { force: true });
    execFileSync("zip", ["-qr", zipPath, "."], { cwd: outDir });
  }

  console.log(`✓ ${edition.padEnd(6)} → dist/mylocalai-${edition}/${zip ? " (+ .zip)" : ""}`);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const args = process.argv.slice(2);
  const zip = args.includes("--zip");
  const requested = args.filter((a) => !a.startsWith("--"));
  const unknown = requested.filter((e) => !EDITIONS[e]);
  if (unknown.length) {
    console.error(`Unknown edition(s): ${unknown.join(", ")}. Choose from: ${Object.keys(EDITIONS).join(", ")}`);
    process.exit(1);
  }
  for (const edition of requested.length ? requested : Object.keys(EDITIONS)) {
    build(edition, { zip });
  }
}
